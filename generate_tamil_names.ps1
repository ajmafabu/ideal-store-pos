function Get-TamilName {
    param([string]$EnglishName)
    if ([string]::IsNullOrWhiteSpace($EnglishName)) { return "" }
    $name = $EnglishName.Trim()
    $nameLower = $name.ToLower().Trim()
    $words = $name -split '\s+'
    $tamilWords = @()
    foreach ($word in $words) {
        $wordLower = $word.ToLower().Trim()
        if ($W.ContainsKey($wordLower)) { $tamilWords += $W[$wordLower] }
        elseif ($wordLower -match '^\d+[\.\d]*$') { $tamilWords += $word }
        else { $tamilWords += $word }
    }
    return ($tamilWords -join ' ').Trim()
}

