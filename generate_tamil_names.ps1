        $updateData += @{ id = $product.id; tamil_name = $tamilName; name = $product.name }
    }
}
Write-Host "Generated $($updateData.Count) Tamil names" -ForegroundColor Green

# Show samples
Write-Host ""
Write-Host "Samples:" -ForegroundColor Cyan
for ($i = 0; $i -lt [Math]::Min(15, $updateData.Count); $i++) {
    $d = $updateData[$i]
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($d.tamil_name)
    $hex = ($bytes | ForEach-Object { $_.ToString("X2") }) -join " "
    Write-Host "  $($d.name) => $($d.tamil_name) [UTF8: $hex]" -ForegroundColor Gray
}

# Generate SQL UPDATE statements
Write-Host ""
Write-Host "Generating SQL UPDATE script..." -ForegroundColor Yellow

$sqlLines = @()
$sqlLines += "-- Tamil Name Update Script"
$sqlLines += "-- Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
$sqlLines += "-- Products to update: $($updateData.Count)"
$sqlLines += ""
$sqlLines += "DO $$"
$sqlLines += "DECLARE"
$sqlLines += "  rec RECORD;"
$sqlLines += "BEGIN"

foreach ($item in $updateData) {
    $escapedName = $item.tamil_name.Replace("'", "''")
    $sqlLines += "  UPDATE products SET tamil_name = E'$escapedName' WHERE id = '$($item.id)' AND (tamil_name IS NULL OR tamil_name = '');"
}

$sqlLines += "END $$;"
$sqlLines += ""
$sqlLines += "-- Verify:"
$sqlLines += "SELECT count(*) as updated FROM products WHERE tamil_name IS NOT NULL AND tamil_name != '';"

$sqlContent = $sqlLines -join "`n"
[System.IO.File]::WriteAllText($SqlOutputPath, $sqlContent, [System.Text.Encoding]::UTF8)
Write-Host "SQL saved to: $SqlOutputPath" -ForegroundColor Green

